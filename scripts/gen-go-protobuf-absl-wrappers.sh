#!/usr/bin/env bash
# Regenerate internal/ccall/go-protobuf/protobuf/absl_plain_wrap_*.cc
# (one Abseil .cc per translation unit — required so anonymous-namespace
# helpers in Abseil do not collide when linked with the go-protobuf amalgamation).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
PY=python3
exec "$PY" <<'PY'
import os, re
ABSL = "internal/ccall/absl"
GO_ABSL = "internal/ccall/go-absl"
OUT = "internal/ccall/go-protobuf/protobuf"

def expand(entry):
    seen = set()
    stack = [entry]
    order = []
    while stack:
        rel = stack.pop()
        if rel in seen:
            continue
        seen.add(rel)
        path = os.path.join(GO_ABSL, rel)
        if not os.path.isfile(path):
            continue
        text = open(path).read()
        for m in re.finditer(r'#include "go-absl/([^"]+)"', text):
            inc = m.group(1)
            if inc.endswith("export.inc"):
                stack.append(inc)
        for m in re.finditer(r'#include "(absl/[^"]+\.cc)"', text):
            order.append(m.group(1))
    out = []
    for x in order:
        if x not in out:
            out.append(x)
    return out

merged = []
for entry in (
    "log/go_internal/log_message/export.inc",
    "log/go_internal/check_op/export.inc",
    "strings/cord/export.inc",
):
    p = os.path.join(GO_ABSL, entry)
    if not os.path.isfile(p):
        continue
    for x in expand(entry):
        if x not in merged:
            merged.append(x)

SKIP = {"absl/numeric/int128.cc"}
ALREADY_IN_PLAIN_LINK = {
    "absl/base/internal/raw_logging.cc",
    "absl/hash/internal/city.cc",
    "absl/hash/internal/low_level_hash.cc",
    "absl/hash/internal/hash.cc",
}
final = [x for x in merged if x not in SKIP and x not in ALREADY_IN_PLAIN_LINK]

header = (
    "// Generated by scripts/gen-go-protobuf-absl-wrappers.sh — do not edit.\n"
    "// See absl_plain_link.inc.\n\n"
)
for name in os.listdir(OUT):
    if name.startswith("absl_plain_wrap_") and name.endswith(".cc") and "int128" not in name:
        os.remove(os.path.join(OUT, name))
for i, rel in enumerate(final):
    safe = rel.replace("/", "_").replace(".cc", "")
    fname = f"absl_plain_wrap_{i:03d}_{safe}.cc"
    with open(os.path.join(OUT, fname), "w") as f:
        f.write(header)
        f.write(f'#include "../../{rel}"\n')
# absl::uint128 / kuint128max (omitted from closure — overlaps protobuf stubs if amalgamated twice).
with open(os.path.join(OUT, "absl_plain_wrap_int128.cc"), "w") as f:
    f.write(header)
    f.write('#include "../../absl/numeric/int128.cc"\n')
print("Wrote", len(final), "+ int128 wrapper files to", OUT)
PY
