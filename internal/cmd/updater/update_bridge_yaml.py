def find_cc_proto_libraries(ccall_dir: str) -> list[dict]:
    """Scan BUILD files for cc_proto_library targets."""
    results = []
    zetasql_dir = os.path.join(ccall_dir, "zetasql")
    for root, dirs, files in os.walk(zetasql_dir):
        for fname in files:
            if fname not in ("BUILD", "BUILD.bazel"):
                continue
            build_path = os.path.join(root, fname)
            rel_dir = os.path.relpath(root, ccall_dir)
            with open(build_path) as f:
                build_content = f.read()
            for m in re.finditer(
                r"cc_proto_library\s*\((.*?)\)", build_content, re.DOTALL,
            ):
                block = m.group(1)
                name_match = re.search(r'name\s*=\s*"(\w+)"', block)
                if not name_match:
                    continue
                target_name = name_match.group(1)
                full_name = f"{rel_dir}/{target_name}"
                deps = []
                deps_match = re.search(
                    r"deps\s*=\s*\[(.*?)\]", block, re.DOTALL
                )
                if deps_match:
                    for dep_m in re.finditer(r'"([^"]+)"', deps_match.group(1)):
                        dep_str = dep_m.group(1).lstrip("/").replace(":", "/")
                        deps.append(dep_str)
                results.append({"name": full_name, "deps": deps})
    return results


# ---------------------------------------------------------------------------
# Deduplication
# ---------------------------------------------------------------------------

def deduplicate_methods(methods: list[Method]) -> list[Method]:
    """Remove duplicate method entries, keeping the first occurrence."""
    seen: set[str] = set()
    result: list[Method] = []
    for m in methods:
        if m.name not in seen:
            seen.add(m.name)
            result.append(m)
    return result


