#!/usr/bin/env python3
"""
update_bridge_yaml.py

Regenerates bridge.yaml (and optionally config.yaml protoc entries) after
a ZetaSQL source update.

Architecture
------------
bridge.yaml has three tiers of content:

  1. **Mechanical – Resolved AST** (package zetasql/public/analyzer)
     Generated by parsing resolved_ast.h, which is itself machine-generated.
     Each Resolved* class gets getter/setter/adder bridge entries.

  2. **Mechanical – Parser AST** (package zetasql/parser/parser)
     Generated by parsing parse_tree_generated.h (also machine-generated).
     Each AST* class gets getter/setter entries, plus _num/indexed pairs for
     Span<> collections.

  3. **Manual – everything else** (sql_formatter, catalog, simple_catalog)
     Hand-curated API surface.  Preserved verbatim from the old bridge.yaml.

The script:
  - Reads the OLD bridge.yaml to extract manual entries.
  - Parses the NEW C++ headers to regenerate mechanical entries.
  - Merges the two and writes out a new bridge.yaml.

Usage
-----
    python3 update_bridge_yaml.py \\
        --ccall-dir path/to/internal/ccall \\
        --old-bridge bridge.yaml \\
        --output     bridge.yaml.new

Then diff and review before replacing bridge.yaml.

Type-mapping rules (C++ -> bridge.yaml)
---------------------------------------
    const std::string&           -> string
    std::string                  -> string
    absl::string_view            -> string
    const Type*, const Value&    -> struct
    std::vector<T>               -> struct  (getter/setter)
    std::unique_ptr<T>           -> struct
    absl::Span<T>               -> struct  (_num + indexed)
    bool                         -> bool (getter return), int (setter arg)
    int, int32_t, int64_t        -> int
    enum types                   -> int
    size_t, uint32_t             -> uint32  (rare)
    IdString                     -> string  (via GetAsString/SetIdentifier)
"""

