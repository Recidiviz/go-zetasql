# Methods to skip in parser AST
PARSER_SKIP = {
    "Accept", "InitFields", "SingleNodeDebugString",
}

PARSER_SKIP_PREFIXES = ("Accept",)


def parse_parser_ast(header_path: str) -> list[Method]:
    """Parse parse_tree_generated.h and generate bridge.yaml Method entries."""
    with open(header_path) as f:
        content = f.read()

    methods: list[Method] = []

    for class_name, public_body in extract_class_bodies(content, "AST"):
        seen_names: set[str] = set()

        # --- Span collections ---
        # const absl::Span<const ASTFoo* const>& field() const
        for m in re.finditer(
            r"const\s+absl::Span<\s*const\s+(\w+)\*\s*const\s*>&?\s+"
            r"(\w+)\s*\(\s*\)\s*const",
            public_body,
        ):
            element_type = m.group(1)
            field_name = m.group(2)

            # _num entry
            methods.append(Method(
                name=f"{class_name}_{field_name}_num",
                args=["struct"], ret=["int"],
            ))
            seen_names.add(field_name)

            # Look for indexed overload: const T* name(int i) const
            idx_pat = re.compile(
                rf"const\s+{re.escape(element_type)}\*\s+(\w+)\s*\(\s*int\s+\w+\s*\)\s*const",
            )
            idx_m = idx_pat.search(public_body, m.end())
            if idx_m:
                accessor_name = idx_m.group(1)
                methods.append(Method(
                    name=f"{class_name}_{accessor_name}",
                    args=["struct", "int"], ret=["struct"],
                ))
                seen_names.add(accessor_name)

        # --- num_xxx() / xxx(int) pairs (non-Span style) ---
        for m in re.finditer(
            r"^\s*int\s+(num_\w+)\s*\(\s*\)\s*const",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name in seen_names:
                continue
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct"], ret=["int"],
            ))
            seen_names.add(name)

            # Look for indexed accessor after this
            rest = public_body[m.end():]
            idx_m = re.search(
                r"const\s+(\w+)\*\s+(\w+)\s*\(\s*int\s+\w+\s*\)\s*const",
                rest,
            )
            if idx_m and idx_m.start() < 200:  # within ~5 lines
                accessor_name = idx_m.group(2)
                if accessor_name not in seen_names:
                    methods.append(Method(
                        name=f"{class_name}_{accessor_name}",
                        args=["struct", "int"], ret=["struct"],
                    ))
                    seen_names.add(accessor_name)

        # --- Child node pointer getters: const ASTFoo* foo() const ---
        for m in re.finditer(
            r"const\s+(AST\w+)\*\s+(\w+)\s*\(\s*\)\s*const\b",
            public_body,
        ):
            name = m.group(2)
            if name in PARSER_SKIP or name in seen_names:
                continue
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct"], ret=["struct"],
            ))
            seen_names.add(name)

        # --- Boolean getters: bool foo() const ---
        for m in re.finditer(
            r"^\s*bool\s+(\w+)\s*\(\s*\)\s*const\b",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name in PARSER_SKIP or name in seen_names:
                continue
            # Skip most Is* methods except specific ones
            if name.startswith("Is"):
                if name in ("IsTableExpression", "IsAllowedInComparison",
                            "IsLoopStatement", "IsTableParameter",
                            "IsTemplated"):
                    pass  # include these
                else:
                    continue
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct"], ret=["bool"],
            ))
            seen_names.add(name)

        # --- Boolean/enum setters: void set_foo(Type) ---
        for m in re.finditer(
            r"^\s*void\s+(set_\w+)\s*\(\s*(\w+)\s+\w+\s*\)",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            arg_type = m.group(2)
            if name in seen_names:
                continue
            if arg_type == "bool":
                bridge_arg = "int"
            elif arg_type in ("int", "int32_t", "int64_t"):
                bridge_arg = "int"
            elif arg_type in ("std::string", "string"):
                bridge_arg = "string"
            else:
                bridge_arg = "int"  # enums
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct", bridge_arg],
            ))
            seen_names.add(name)

        # --- String setters: void set_foo(std::string val) ---
        for m in re.finditer(
            r"^\s*void\s+(set_\w+)\s*\(\s*std::string\s+\w+\s*\)",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name in seen_names:
                continue
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct", "string"],
            ))
            seen_names.add(name)

        # --- IdString setter: void SetIdentifier(IdString id) ---
        for m in re.finditer(
            r"^\s*void\s+(SetIdentifier)\s*\(\s*IdString\s+\w+\s*\)",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name not in seen_names:
                methods.append(Method(
                    name=f"{class_name}_{name}",
                    args=["struct", "string"],
                ))
                seen_names.add(name)

        # --- std::string GetAsString() const / GetSQLFor*() ---
        for m in re.finditer(
            r"^\s*std::string\s+(\w+)\s*\(\s*\)\s*const\b",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name in seen_names:
                continue
            if name in ("GetAsString", "GetSQLForOperator",
                        "GetSQLForDirection", "GetSQLForNullOrder",
                        "GetSQLForJoinType", "GetSQLForJoinHint",
                        "GetSQLForAlterAction", "GetSQLForOperation",
                        "GetSQLForInsertMode", "GetSQLForMatchType",
                        "GetSQLForUnit", "GetSqlForStoredMode",
                        "GetFrameUnitString",
                        "ContainsAttribute"):
                methods.append(Method(
                    name=f"{class_name}_{name}",
                    args=["struct"], ret=["string"],
                ))
                seen_names.add(name)

        # --- std::string ToIdentifierPathString(size_t) const ---
        for m in re.finditer(
            r"^\s*std::string\s+(ToIdentifierPathString)\s*\("
            r"\s*(?:size_t|uint32_t)\s+\w+\s*(?:=\s*\d+)?\s*\)\s*const",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name not in seen_names:
                methods.append(Method(
                    name=f"{class_name}_{name}",
                    args=["struct", "uint32"], ret=["string"],
                ))
                seen_names.add(name)

        # --- absl::string_view image() const (ASTLeaf) ---
        for m in re.finditer(
            r"^\s*absl::string_view\s+(image)\s*\(\s*\)\s*const",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name not in seen_names:
                methods.append(Method(
                    name=f"{class_name}_{name}",
                    args=["struct"], ret=["string"],
                ))
                seen_names.add(name)

        # --- Enum getters: EnumType foo() const { return foo_; } ---
        for m in re.finditer(
            r"^\s*(\w+)\s+(\w+)\s*\(\s*\)\s*const\s*\{[^}]*return\s+\w+_\s*;",
            public_body,
            re.MULTILINE,
        ):
            ret_type = m.group(1)
            name = m.group(2)
            if name in seen_names or name in PARSER_SKIP:
                continue
            # Must not be a known primitive type
            if ret_type in ("bool", "int", "void", "std::string",
                            "absl::string_view", "friend", "static",
                            "virtual", "explicit", "const"):
                continue
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct"], ret=["int"],
            ))
            seen_names.add(name)

        # --- bool is_hex() const; (declaration only, no inline body) ---
        for m in re.finditer(
            r"^\s*bool\s+(\w+)\s*\(\s*\)\s*const\s*;",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name not in seen_names and not name.startswith("Is"):
                methods.append(Method(
                    name=f"{class_name}_{name}",
                    args=["struct"], ret=["bool"],
                ))
                seen_names.add(name)

        # --- std::string GetAsString() const; (declaration only) ---
        for m in re.finditer(
            r"^\s*std::string\s+(\w+)\s*\(\s*\)\s*const\s*;",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            if name not in seen_names and name in (
                "GetAsString", "GetSQLForOperator",
                "GetSQLForDirection", "GetSQLForNullOrder",
                "GetSQLForJoinType", "GetSQLForJoinHint",
                "GetSQLForAlterAction",
            ):
                methods.append(Method(
                    name=f"{class_name}_{name}",
                    args=["struct"], ret=["string"],
                ))
                seen_names.add(name)

    return methods


