def main():
    parser = argparse.ArgumentParser(
        description="Regenerate bridge.yaml after a ZetaSQL source update.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
            Example:
              cd internal/cmd/generator
              python3 ../updater/update_bridge_yaml.py \\
                  --ccall-dir ../../ccall \\
                  --old-bridge bridge.yaml \\
                  --output bridge.yaml.new

            Then diff bridge.yaml bridge.yaml.new and review.
        """),
    )
    parser.add_argument(
        "--ccall-dir",
        default=os.path.join(os.path.dirname(__file__), "..", "..", "ccall"),
        help="Path to internal/ccall directory",
    )
    parser.add_argument(
        "--old-bridge",
        default=os.path.join(
            os.path.dirname(__file__), "..", "generator", "bridge.yaml"
        ),
        help="Path to existing bridge.yaml to preserve manual entries from",
    )
    parser.add_argument(
        "--output", "-o",
        default=None,
        help="Output path (default: stdout)",
    )
    parser.add_argument(
        "--dump-protoc",
        action="store_true",
        help="Also dump detected cc_proto_library targets for config.yaml",
    )
    args = parser.parse_args()

    ccall_dir = os.path.abspath(args.ccall_dir)
    resolved_ast_h = os.path.join(
        ccall_dir, "zetasql", "resolved_ast", "resolved_ast.h"
    )
    parse_tree_h = os.path.join(
        ccall_dir, "zetasql", "parser", "parse_tree_generated.h"
    )

    for p in (resolved_ast_h, parse_tree_h):
        if not os.path.isfile(p):
            print(f"ERROR: Cannot find {p}", file=sys.stderr)
            sys.exit(1)

    if not os.path.isfile(args.old_bridge):
        print(f"ERROR: Cannot find old bridge.yaml at {args.old_bridge}", file=sys.stderr)
        sys.exit(1)

    # --- Step 1: Preserve manual packages ---
    print("Loading old bridge.yaml...", file=sys.stderr)
    old_packages = parse_bridge_yaml(args.old_bridge)
    manual_packages = [
        p for p in old_packages if p.name not in MECHANICAL_PACKAGES
    ]
    print(
        f"  {len(old_packages)} packages total, "
        f"{len(manual_packages)} manual (preserved)",
        file=sys.stderr,
    )

    # --- Step 2: Parse resolved_ast.h ---
    print("Parsing resolved_ast.h...", file=sys.stderr)
    resolved_methods = parse_resolved_ast(resolved_ast_h)
    print(f"  {len(resolved_methods)} method entries", file=sys.stderr)

    # --- Step 3: Parse parse_tree_generated.h ---
    print("Parsing parse_tree_generated.h...", file=sys.stderr)
    parser_methods = parse_parser_ast(parse_tree_h)
    print(f"  {len(parser_methods)} method entries", file=sys.stderr)

    # --- Step 4: Build mechanical packages ---
    # Get the old mechanical packages for carry-forward
    old_parser_pkg = next(
        (p for p in old_packages if p.name == "zetasql/parser/parser"), None
    )
    old_analyzer_pkg = next(
        (p for p in old_packages if p.name == "zetasql/public/analyzer"), None
    )

    # Parser package: base entries + generated + carry-forward
    parser_base = parser_ast_base_entries()
    parser_generated = deduplicate_methods(parser_base + parser_methods)
    parser_generated_names = {m.name for m in parser_generated}
    parser_carried = []
    if old_parser_pkg:
        parser_carried = carry_forward_entries(
            old_parser_pkg, PARSER_CARRY_FORWARD_PREFIXES,
            parser_generated_names,
        )
    parser_pkg = Package(
        name="zetasql/parser/parser",
        methods=deduplicate_methods(parser_generated + parser_carried),
    )

    # Analyzer package: base entries + generated + carry-forward
    analyzer_base = resolved_ast_base_entries()
    analyzer_generated = deduplicate_methods(analyzer_base + resolved_methods)
    analyzer_generated_names = {m.name for m in analyzer_generated}
    analyzer_carried = []
    if old_analyzer_pkg:
        analyzer_carried = carry_forward_entries(
            old_analyzer_pkg, ANALYZER_CARRY_FORWARD_PREFIXES,
            analyzer_generated_names,
        )
    if analyzer_carried:
        print(
            f"  Carried forward {len(analyzer_carried)} entries from old yaml "
            f"(AnalyzerOptions, LanguageOptions, etc.)",
            file=sys.stderr,
        )
    analyzer_pkg = Package(
        name="zetasql/public/analyzer",
        methods=deduplicate_methods(analyzer_generated + analyzer_carried),
    )

    # --- Step 5: Assemble in original order ---
    final_packages: list[Package] = []
    for p in manual_packages:
        if p.name == "zetasql/public/sql_formatter":
            final_packages.append(p)
    final_packages.append(parser_pkg)
    for p in manual_packages:
        if p.name != "zetasql/public/sql_formatter":
            final_packages.append(p)
    final_packages.append(analyzer_pkg)

    # --- Step 6: Diff report ---
    print("\nFinal output:", file=sys.stderr)
    for p in final_packages:
        print(f"  {p.name}: {len(p.methods)} methods", file=sys.stderr)

    for old_pkg in old_packages:
        if old_pkg.name not in MECHANICAL_PACKAGES:
            continue
        new_pkg = (
            parser_pkg if old_pkg.name == "zetasql/parser/parser"
            else analyzer_pkg
        )
        old_names = {m.name for m in old_pkg.methods}
        new_names = {m.name for m in new_pkg.methods}
        added = sorted(new_names - old_names)
        removed = sorted(old_names - new_names)
        if added:
            print(f"\n  {old_pkg.name}: {len(added)} NEW methods:", file=sys.stderr)
            for n in added[:25]:
                print(f"    + {n}", file=sys.stderr)
            if len(added) > 25:
                print(f"    ... and {len(added) - 25} more", file=sys.stderr)
        if removed:
            print(f"\n  {old_pkg.name}: {len(removed)} REMOVED (check manually):", file=sys.stderr)
            for n in removed[:25]:
                print(f"    - {n}", file=sys.stderr)
            if len(removed) > 25:
                print(f"    ... and {len(removed) - 25} more", file=sys.stderr)

    # --- Step 7: Write ---
    output = emit_yaml(final_packages)
    if args.output:
        with open(args.output, "w") as f:
            f.write(output)
        print(f"\nWrote {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(output)

    if args.dump_protoc:
        print("\n--- Detected cc_proto_library targets ---", file=sys.stderr)
        protos = find_cc_proto_libraries(ccall_dir)
        for p in sorted(protos, key=lambda x: x["name"]):
            print(f"  - name: {p['name']}", file=sys.stderr)
            if p["deps"]:
                print("    deps:", file=sys.stderr)
                for d in p["deps"]:
                    print(f"      - {d}", file=sys.stderr)

    print("\nDone. Diff the output against old bridge.yaml to review.", file=sys.stderr)
    print("WARNING: bridge.inc files need manual updates for new/changed APIs.", file=sys.stderr)


if __name__ == "__main__":
    main()
