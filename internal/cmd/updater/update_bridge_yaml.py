# Infrastructure methods to always skip
RESOLVED_SKIP = {
    "node_kind", "node_kind_string",
    "CheckFieldsAccessedImpl", "CheckNoFieldsAccessed",
    "ClearFieldsAccessed", "MarkFieldsAccessed",
    "GetTreeDepth", "GetChildNodes", "AddMutableChildNodePointers",
    "CollectDebugStringFields",
}

RESOLVED_SKIP_PREFIXES = (
    "Accept", "ChildrenAccept", "SaveTo", "RestoreFrom",
    "CollectDebugString", "GetParseLocationRange",
)


def parse_resolved_ast(header_path: str) -> list[Method]:
    """Parse resolved_ast.h and generate bridge.yaml Method entries."""
    with open(header_path) as f:
        content = f.read()

    methods: list[Method] = []

    for class_name, public_body in extract_class_bodies(content, "Resolved"):
        # --- Getters ---
        # Matches: const Value& value() const
        #          bool flag() const
        #          int field() const
        #          const Type* type() const
        #          ResolvedNodeKind node_kind() const
        #          const std::vector<...>& list() const
        for m in re.finditer(
            r"^\s*((?:const\s+)?[\w:<>]+(?:\s*[*&])?)\s+"  # return type
            r"(\w+)\s*\(\s*\)\s*const\b",                  # method_name() const
            public_body,
            re.MULTILINE,
        ):
            ret_type = m.group(1).strip()
            name = m.group(2)

            if name in RESOLVED_SKIP:
                continue
            if any(name.startswith(p) for p in RESOLVED_SKIP_PREFIXES):
                continue
            # Skip template Is<>/GetAs<> (they have < in the body)
            if name in ("Is", "GetAs"):
                continue
            # Skip IsFoo / GetAsFoo on non-base classes
            if name.startswith("Is") and class_name != "ResolvedNode":
                continue
            if name.startswith("GetAs"):
                continue

            bridge_ret = map_return_type(ret_type)
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct"],
                ret=[bridge_ret],
            ))

        # --- Vector getters (multi-line type spanning) ---
        for m in re.finditer(
            r"^\s*const\s+std::vector<(.+?)>&?\s+(\w+)\s*\(\s*\)\s*const",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(2)
            # Avoid duplicate if already caught above
            full_name = f"{class_name}_{name}"
            if not any(mt.name == full_name for mt in methods):
                methods.append(Method(
                    name=full_name, args=["struct"], ret=["struct"],
                ))

        # --- Setters: void set_foo(Type v) ---
        for m in re.finditer(
            r"^\s*void\s+(set_\w+)\s*\("
            r"\s*((?:const\s+)?[\w:<>&* ]+?(?:<[^>]*>)?[\s&*]*)"
            r"\s+\w+\s*\)",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            arg_type = m.group(2).strip()
            if "std::vector" in arg_type or "unique_ptr" in arg_type:
                bridge_arg = "struct"
            else:
                bridge_arg = map_setter_arg(arg_type)
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct", bridge_arg],
            ))

        # --- Adders: void add_foo(Type v) ---
        for m in re.finditer(
            r"^\s*void\s+(add_\w+)\s*\("
            r"\s*((?:const\s+)?[\w:<>&* ]+?(?:<[^>]*>)?[\s&*]*)"
            r"\s+\w+\s*\)",
            public_body,
            re.MULTILINE,
        ):
            name = m.group(1)
            arg_type = m.group(2).strip()
            if "unique_ptr" in arg_type:
                bridge_arg = "struct"
            else:
                bridge_arg = map_setter_arg(arg_type)
            methods.append(Method(
                name=f"{class_name}_{name}",
                args=["struct", bridge_arg],
            ))

    return methods


